private let now = Date(timeIntervalSince1970: 1_800_000_000)
private let safari = ClipboardSourceApp(bundleID: "com.apple.Safari", name: "Safari")

/// Stands in for the pasteboard and counts every read of the content.
@MainActor
private final class FakePasteboard: PasteboardReading {
    var typeNames: [String] = ["public.utf8-plain-text"]
    var text: String?
    var source: String?
    var paths: [String] = []
    var color: String?
    var image: Data?
    private(set) var contentReads = 0

    init(text: String? = nil) {
        self.text = text
    }

    func plainText() -> String? {
        contentReads += 1
        return text
    }

    func declaredSource() -> String? {
        contentReads += 1
        return source
    }

    func filePaths() -> [String] {
        contentReads += 1
        return paths
    }

    func colorHex() -> String? {
        contentReads += 1
        return color
    }

    func imagePNG(limit: Int) -> Data? {
        contentReads += 1
        return image.flatMap { $0.count <= limit ? $0 : nil }
    }
}

@MainActor
struct ClipboardCaptureTests {
    private func capture(
        _ pasteboard: FakePasteboard,
        app: ClipboardSourceApp? = safari,
        settings: ClipboardSettings = ClipboardSettings()
    ) -> ClipboardCapture? {
        ClipboardReader.capture(from: pasteboard, app: app, settings: settings, at: now)
    }

    @Test(arguments: [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
    ])
    func markedContentIsNeverEvenRead(type: String) {
        let pasteboard = FakePasteboard(text: "hunter2")
        pasteboard.typeNames.append(type)

        #expect(capture(pasteboard) == nil)
        #expect(pasteboard.contentReads == 0)
    }

    @Test(arguments: ClipboardSettings.defaultExcludedApps)
    func passwordManagersAreExcludedWithoutReadingAnything(bundleID: String) {
        let pasteboard = FakePasteboard(text: "hunter2")

        #expect(capture(pasteboard, app: ClipboardSourceApp(bundleID: bundleID, name: "Vault")) == nil)
        #expect(pasteboard.contentReads == 0)
    }

    @Test func anExcludedAppInTheBackgroundIsCaughtByItsDeclaredSource() {
        let pasteboard = FakePasteboard(text: "hunter2")
        pasteboard.source = "com.bitwarden.desktop"

        #expect(capture(pasteboard) == nil)
    }

    @Test func theUserCanExcludeMoreApps() {
        var settings = ClipboardSettings()
        settings.excludedApps = ["com.apple.Safari"]

        #expect(capture(FakePasteboard(text: "hello"), settings: settings) == nil)
    }

    @Test(arguments: [
        ("hello", ClipboardKind.text), ("https://github.com/acme/app", .link), ("http://a.example", .link),
        ("see https://a.example now", .text), ("ftp://a.example", .text), ("#6B5BB5", .color), ("#FFF", .color),
        ("#12345678", .color), ("#12", .text), ("#GGGGGG", .text), ("12345", .text),
    ])
    func classifiesText(text: String, expected: ClipboardKind) {
        #expect(ClipboardReader.kind(of: text) == expected)
    }

    @Test func keepsTheSourceAppName() {
        #expect(capture(FakePasteboard(text: "hello"))?.entry.appName == "Safari")
    }

    @Test func filesWinOverTheirNamesAsText() {
        let pasteboard = FakePasteboard(text: "a.pdf")
        pasteboard.paths = ["/tmp/a.pdf", "/tmp/b.pdf"]

        let entry = capture(pasteboard)?.entry

        #expect(entry?.kind == .file)
        #expect(entry?.paths == ["/tmp/a.pdf", "/tmp/b.pdf"])
        #expect(entry?.title == "a.pdf +1")
    }

    @Test func textWinsOverThePictureOfIt() {
        let pasteboard = FakePasteboard(text: "cell")
        pasteboard.image = pngData()

        #expect(capture(pasteboard)?.entry.kind == .text)
    }

    @Test func aColorObjectBecomesItsHex() {
        let pasteboard = FakePasteboard()
        pasteboard.color = "#112233"

        #expect(capture(pasteboard)?.entry.kind == .color)
        #expect(capture(pasteboard)?.entry.text == "#112233")
    }

    @Test func readsImageSize() throws {
        let pasteboard = FakePasteboard()
        pasteboard.image = pngData()

        let result = try #require(capture(pasteboard))

        #expect(result.entry.kind == .image)
        #expect(result.entry.pixelWidth == 3)
        #expect(result.entry.pixelHeight == 2)
        #expect(result.image == pasteboard.image)
        #expect(result.entry.imageName?.hasSuffix(".png") == true)
    }

    @Test func anImageOverTenMegabytesIsNotKept() {
        let pasteboard = FakePasteboard()
        pasteboard.image = Data(count: ClipboardReader.imageLimit + 1)

        #expect(capture(pasteboard) == nil)
    }

    @Test(arguments: ["", "   \n "])
    func nothingWorthKeeping(text: String) {
        #expect(capture(FakePasteboard(text: text)) == nil)
    }

    @Test func veryLongTextIsLeftOut() {
        #expect(capture(FakePasteboard(text: String(repeating: "a", count: ClipboardReader.textLimit + 1))) == nil)
    }

    private func pngData() -> Data {
        let bitmap = NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: 3, pixelsHigh: 2, bitsPerSample: 8, samplesPerPixel: 4,
            hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
        )
        return bitmap?.representation(using: .png, properties: [:]) ?? Data()
    }
}

struct ClipboardHistoryTests {
    private func entry(_ text: String, age: TimeInterval = 0) -> ClipboardEntry {
        ClipboardEntry(
            kind: .text,
            text: text,
            byteCount: text.utf8.count,
            appName: "Notes",
            date: now.addingTimeInterval(-age),
            fingerprint: "text:\(text)"
        )
    }

    @Test func newestComesFirst() {
        var history = ClipboardHistory()
        history.insert(entry("a"))
        history.insert(entry("b"))

        #expect(history.entries.map(\.text) == ["b", "a"])
    }

    @Test func copyingAgainMovesToTheTopAndKeepsThePin() throws {
        var history = ClipboardHistory()
        history.insert(entry("a"))
        try history.togglePin(#require(history.entries.first).id)
        history.insert(entry("b"))

        let replaced = history.insert(entry("a"))

        #expect(replaced?.text == "a")
        #expect(history.entries.map(\.text) == ["a", "b"])
        #expect(history.entries.first?.isPinned == true)
    }

    @Test func keepsAtMostFiveHundredEntries() {
        var history = ClipboardHistory(entries: (0 ..< 510).map { entry("\($0)", age: Double($0)) })

        let removed = history.prune(at: now, retentionDays: 30)

        #expect(history.entries.count == 500)
        #expect(history.entries.last?.text == "499")
        #expect(removed.count == 10)
    }

    @Test func expiresAfterThirtyDays() {
        let day = 86400.0
        var history = ClipboardHistory(entries: [entry("new", age: 29 * day), entry("old", age: 31 * day)])

        history.prune(at: now, retentionDays: 30)

        #expect(history.entries.map(\.text) == ["new"])
    }

    @Test func pinnedEntriesStayForever() {
        var old = entry("keep", age: 400 * 86400)
        old.isPinned = true
        var history = ClipboardHistory(entries: [old, entry("gone", age: 400 * 86400)])

        history.prune(at: now, retentionDays: 30)

        #expect(history.entries.map(\.text) == ["keep"])
    }

    @Test func pinnedEntriesCountTowardsTheLimitButAreNeverTheOnesDropped() {
        var pinned = entry("pinned", age: 1000)
        pinned.isPinned = true
        var history = ClipboardHistory(entries: [entry("a"), entry("b", age: 1), pinned])

        history.prune(at: now, retentionDays: 30, limit: 2)

        #expect(history.entries.map(\.text) == ["a", "pinned"])
    }

    @Test func clearAllKeepsPinnedEntries() throws {
        var history = ClipboardHistory(entries: [entry("a"), entry("b")])
        try history.togglePin(#require(history.entries.first).id)

        let removed = history.removeUnpinned()

        #expect(removed.map(\.text) == ["b"])
        #expect(history.entries.map(\.text) == ["a"])
    }

    @Test func searchIgnoresCaseAndLooksAtTheApp() {
        let history = ClipboardHistory(entries: [entry("Deploy port 8080"), entry("other")])

        #expect(history.matching("PORT", kind: nil).map(\.text) == ["Deploy port 8080"])
        #expect(history.matching("notes", kind: nil).count == 2)
        #expect(history.matching("", kind: .image).isEmpty)
    }

    @Test func titleIsTheFirstLine() {
        #expect(entry("\nfirst\nsecond").title == "first")
    }
}

