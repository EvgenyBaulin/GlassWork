    }
}

@MainActor
struct ClipboardStoreTests {
    private func capture(_ text: String, image: Data? = nil) -> ClipboardCapture {
        var entry = ClipboardEntry(
            kind: image == nil ? .text : .image,
            text: text,
            byteCount: text.utf8.count,
            appName: nil,
            date: now,
            fingerprint: "\(text)"
        )
        entry.imageName = image == nil ? nil : "\(entry.id.uuidString).png"
        return ClipboardCapture(entry: entry, image: image)
    }

    @Test func aNewStoreLeavesTheDiskAlone() {
        let folder = temporaryFolder()

        _ = ClipboardStore(folder: folder)

        #expect(!FileManager.default.fileExists(atPath: folder.path(percentEncoded: false)))
    }

    @Test func theHistoryComesBackAfterARelaunch() async {
        let folder = temporaryFolder()
        let store = ClipboardStore(folder: folder)
        store.add(capture("hello"))
        await store.flush()

        let relaunched = ClipboardStore(folder: folder)
        await relaunched.load(at: now)

        #expect(relaunched.history.entries.map(\.text) == ["hello"])
    }

    @Test func historyFilesAreOnlyForThisUser() async throws {
        let folder = temporaryFolder()
        let store = ClipboardStore(folder: folder)
        store.add(capture("hello"))
        await store.flush()

        let file = folder.appending(path: "history.json").path(percentEncoded: false)
        let attributes = try FileManager.default.attributesOfItem(atPath: file)

        #expect(attributes[.posixPermissions] as? Int == 0o600)
    }

    @Test func deletingAnImageDeletesItsFile() async throws {
        let store = ClipboardStore(folder: temporaryFolder())
        let image = capture("", image: Data([1, 2, 3]))
        store.add(image)
        await store.flush()
        let url = try #require(store.imageURL(for: image.entry))
        try await waitUntil { FileManager.default.fileExists(atPath: url.path(percentEncoded: false)) }

        store.delete(image.entry)

        try await waitUntil { !FileManager.default.fileExists(atPath: url.path(percentEncoded: false)) }
        #expect(store.history.entries.isEmpty)
    }

    @Test func imagesNothingPointsToAreRemovedAtLaunch() async throws {
        let folder = temporaryFolder()
        let images = folder.appending(path: "Images", directoryHint: .isDirectory)
        try FileManager.default.createDirectory(at: images, withIntermediateDirectories: true)
        let orphan = images.appending(path: "orphan.png")
        try Data([1]).write(to: orphan)

        await ClipboardStore(folder: folder).load(at: now)

        #expect(!FileManager.default.fileExists(atPath: orphan.path(percentEncoded: false)))
    }

    /// Image files are written in the background, so tests wait for the outcome instead of a fixed time.
    private func waitUntil(_ condition: () -> Bool) async throws {
        for _ in 0 ..< 200 where !condition() {
            try await Task.sleep(for: .milliseconds(10))
        }
        #expect(condition())
    }
}
