import CryptoKit
import Foundation
import ImageIO

/// The parts of a pasteboard that capture needs. Tests use a stand-in, never the real one.
@MainActor
public protocol PasteboardReading {
    var typeNames: [String] { get }
    /// Plain text, or nil when there is none.
    func plainText() -> String?
    /// The app that says it wrote the content, from `org.nspasteboard.source`.
    func declaredSource() -> String?
    func filePaths() -> [String]
    /// A color object, as `#RRGGBB`.
    func colorHex() -> String?
    /// An image as PNG, or nil when there is none or it would be over `limit` bytes.
    func imagePNG(limit: Int) -> Data?
}

/// The app in front when something was copied.
public struct ClipboardSourceApp: Sendable, Equatable {
    public var bundleID: String?
    public var name: String?

    public init(bundleID: String?, name: String?) {
        self.bundleID = bundleID
        self.name = name
    }
}

/// Something worth keeping, read from the pasteboard but not yet stored.
public struct ClipboardCapture: Sendable, Equatable {
    public var entry: ClipboardEntry
    /// PNG of an image entry. It goes to its own file, not into the history.
    public var image: Data?
}

/// Decides what may be kept, and reads it only after that.
public enum ClipboardReader {
    public static let imageLimit = 10 * 1000 * 1000
    /// Longer text is left out: the history is one file, read at launch.
    public static let textLimit = 1000 * 1000

    /// Marks from nspasteboard.org. The last one is the same rule's older spelling.
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType",
    ]

    /// Looks only at type names, so a password is never read just to find out it is one.
    public static func isPrivate(types: [String]) -> Bool {
        types.contains(where: privateTypes.contains)
    }

    @MainActor
    public static func capture(
        from pasteboard: any PasteboardReading,
        app: ClipboardSourceApp?,
        settings: ClipboardSettings,
        at date: Date
    ) -> ClipboardCapture? {
        guard !isPrivate(types: pasteboard.typeNames) else { return nil }
        let excluded = Set(settings.excludedApps)
        if let bundleID = app?.bundleID, excluded.contains(bundleID) {
            return nil
        }
        if let declared = pasteboard.declaredSource(), excluded.contains(declared) {
            return nil
        }
        return read(pasteboard, appName: app?.name, at: date)
    }

    /// Files first, because Finder also offers their names as text. Text goes before images, because
    /// office apps add a picture of the same text.
    @MainActor
    private static func read(
        _ pasteboard: any PasteboardReading,
        appName: String?,
        at date: Date
    ) -> ClipboardCapture? {
        let paths = pasteboard.filePaths()
        if !paths.isEmpty {
            return ClipboardCapture(entry: entry(.file, paths.joined(separator: "\n"), appName, date))
        }
        if let text = pasteboard.plainText() {
            return text.isEmpty ? nil : capture(text: text, appName: appName, at: date)
        }
        if let hex = pasteboard.colorHex() {
            return ClipboardCapture(entry: entry(.color, hex, appName, date))
        }
        return pasteboard.imagePNG(limit: imageLimit).flatMap { capture(image: $0, appName: appName, at: date) }
    }

    private static func capture(text: String, appName: String?, at date: Date) -> ClipboardCapture? {
        guard text.utf8.count <= textLimit, !text.allSatisfy(\.isWhitespace) else { return nil }
        return ClipboardCapture(entry: entry(kind(of: text), text, appName, date))
    }

    private static func capture(image: Data, appName: String?, at date: Date) -> ClipboardCapture? {
        guard image.count <= imageLimit else { return nil }
        let digest = SHA256.hash(data: image).map { String(format: "%02x", $0) }.joined()
        var entry = ClipboardEntry(
            kind: .image,
            text: "",
            byteCount: image.count,
            appName: appName,
            date: date,
            fingerprint: "image:\(digest)"
        )
        let size = pixelSize(of: image)
        entry.pixelWidth = size?.width
        entry.pixelHeight = size?.height
        entry.imageName = "\(entry.id.uuidString).png"
        return ClipboardCapture(entry: entry, image: image)
    }

    private static func entry(
        _ kind: ClipboardKind,
        _ text: String,
        _ appName: String?,
        _ date: Date
    ) -> ClipboardEntry {
        ClipboardEntry(
            kind: kind,
            text: text,
            byteCount: text.utf8.count,
            appName: appName,
            date: date,
            fingerprint: "\(kind.rawValue):\(text)"
        )
    }

    /// A whole string that is a web address or a hex color is that thing, not text that mentions one.
    public static func kind(of text: String) -> ClipboardKind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if isHexColor(trimmed) {
            return .color
        }
        guard !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
              url.scheme == "http" || url.scheme == "https", url.host() != nil
        else { return .text }
        return .link
    }

    private static func isHexColor(_ text: String) -> Bool {
        guard text.hasPrefix("#") else { return false }
        let digits = text.dropFirst()
        return [3, 6, 8].contains(digits.count) && digits.allSatisfy(\.isHexDigit)
    }

    private static func pixelSize(of image: Data) -> (width: Int, height: Int)? {
        guard let source = CGImageSourceCreateWithData(image as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int
        else { return nil }
        return (width, height)
    }
}
